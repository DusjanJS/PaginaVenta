-- 1. ESQUEMA

-- CATEGORÍA 
CREATE TABLE categoria (
    id_categoria   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug           VARCHAR(40)  NOT NULL UNIQUE,      
    nombre         VARCHAR(80)  NOT NULL UNIQUE,
    descripcion    TEXT         NOT NULL,
    cta            VARCHAR(60)  NOT NULL,            
    imagen         TEXT         NOT NULL,
    orden          SMALLINT     NOT NULL DEFAULT 0
);

-- PRODUCTO 
CREATE TABLE producto (
    id_producto      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria     INT           NOT NULL REFERENCES categoria(id_categoria) ON DELETE RESTRICT,
    codigo           VARCHAR(10)   NOT NULL UNIQUE CHECK (codigo ~ '^p[0-9]{3}$'), 
    slug             VARCHAR(80)   NOT NULL UNIQUE,
    nombre           VARCHAR(150)  NOT NULL,          
    marca            VARCHAR(80)   NOT NULL,          -
    descripcion      TEXT          NOT NULL,
    tipo_variante    VARCHAR(10)   NOT NULL CHECK (tipo_variante IN ('Acabado','Color')),
                                                      
    precio           NUMERIC(10,2) NOT NULL CHECK (precio >= 0),  
    imagen           TEXT          NOT NULL,
    caracteristicas  JSONB         NOT NULL DEFAULT '[]'::jsonb,  
    especificaciones JSON          NOT NULL DEFAULT '{}'::json,   
    compatibilidad   TEXT          NOT NULL,                       
    valoracion       NUMERIC(2,1)  NOT NULL CHECK (valoracion BETWEEN 0 AND 5),  
    num_resenas      INT           NOT NULL DEFAULT 0 CHECK (num_resenas >= 0),  
    etiqueta         VARCHAR(40),                                  
    destacado        BOOLEAN       NOT NULL DEFAULT FALSE,        
    activo           BOOLEAN       NOT NULL DEFAULT TRUE,
    fecha_creacion   TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_producto_categoria ON producto(id_categoria);

-- CONEXIÓN + PRODUCTO_CONEXIÓN 
CREATE TABLE conexion (
    id_conexion  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE producto_conexion (
    id_producto  INT NOT NULL REFERENCES producto(id_producto) ON DELETE CASCADE,
    id_conexion  INT NOT NULL REFERENCES conexion(id_conexion) ON DELETE CASCADE,
    PRIMARY KEY (id_producto, id_conexion)
);
CREATE INDEX idx_producto_conexion_conexion ON producto_conexion(id_conexion);

-- VARIANTE DE PRODUCTO 

CREATE TABLE variante_producto (
    id_variante     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto     INT          NOT NULL REFERENCES producto(id_producto) ON DELETE CASCADE,
    codigo          VARCHAR(40),                              
    es_base         BOOLEAN      NOT NULL DEFAULT FALSE,
    valor           VARCHAR(60)  NOT NULL,                    
    sku             VARCHAR(40)  NOT NULL UNIQUE,
    stock           INT          NOT NULL DEFAULT 0 CHECK (stock >= 0),
    imagen          TEXT,                                    
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_creacion  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_variante_base CHECK (es_base = (codigo IS NULL)),
    UNIQUE (id_producto, codigo),
    UNIQUE (id_producto, valor),
    UNIQUE (id_variante, id_producto)        
);
CREATE UNIQUE INDEX uq_variante_base ON variante_producto(id_producto) WHERE es_base;  

-- CLIENTE 

CREATE TABLE cliente (
    id_cliente      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(120) NOT NULL,
    apellidos       VARCHAR(160),                              
    email           VARCHAR(254) NOT NULL,
    telefono        VARCHAR(30),
    password_hash   TEXT,                                   
    registrado      BOOLEAN      NOT NULL DEFAULT FALSE,
    rol             VARCHAR(10)  NOT NULL DEFAULT 'cliente' CHECK (rol IN ('cliente','admin')),
    newsletter      BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha_creacion  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_registrado_password CHECK (registrado = FALSE OR password_hash IS NOT NULL),
    CONSTRAINT chk_admin_registrado    CHECK (rol = 'cliente' OR registrado)
);
CREATE UNIQUE INDEX uq_cliente_email ON cliente (lower(email)) WHERE registrado;
CREATE INDEX idx_cliente_email_invitado ON cliente (lower(email)) WHERE NOT registrado;


CREATE FUNCTION descuento_bienvenida_hasta(alta timestamptz) RETURNS timestamptz
LANGUAGE sql IMMUTABLE PARALLEL SAFE SET search_path = ''
AS $$ SELECT ((alta AT TIME ZONE 'UTC') + interval '1 month') AT TIME ZONE 'UTC' $$;


