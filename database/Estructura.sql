-- Trigger: mantener fecha_actualizacion en carrito y pedido 
CREATE FUNCTION set_fecha_actualizacion() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
    NEW.fecha_actualizacion := now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_carrito_actualizacion BEFORE UPDATE ON carrito
    FOR EACH ROW EXECUTE FUNCTION set_fecha_actualizacion();
CREATE TRIGGER trg_pedido_actualizacion BEFORE UPDATE ON pedido
    FOR EACH ROW EXECUTE FUNCTION set_fecha_actualizacion();

-- Vista del catálogo: SKU y opción base + stock total sumando variantes.
-- security_invoker: respeta RLS (sin esto la vista saltaría el bloqueo de anon).
CREATE VIEW v_catalogo WITH (security_invoker = true) AS
SELECT p.id_producto, p.codigo, c.slug AS categoria, p.marca, p.nombre, p.precio,
       p.tipo_variante, vb.valor AS variante_base, vb.sku AS sku_base,
       COALESCE(sum(v.stock) FILTER (WHERE v.activo), 0)::int AS stock_total,
       p.valoracion, p.num_resenas, p.etiqueta, p.destacado, p.activo
FROM producto p
JOIN categoria c          ON c.id_categoria = p.id_categoria
JOIN variante_producto vb ON vb.id_producto = p.id_producto AND vb.es_base
JOIN variante_producto v  ON v.id_producto  = p.id_producto
GROUP BY p.id_producto, p.codigo, c.slug, c.orden, p.marca, p.nombre, p.precio, p.tipo_variante,
         vb.valor, vb.sku, p.valoracion, p.num_resenas, p.etiqueta, p.destacado, p.activo;

