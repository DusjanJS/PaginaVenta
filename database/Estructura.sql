-- PEDIDO + LÍNEA DE PEDIDO 

CREATE SEQUENCE seq_numero_pedido START 1001;


CREATE TABLE pedido (
    id_pedido            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_pedido        VARCHAR(20)   NOT NULL UNIQUE
                         DEFAULT ('UC-' || to_char(now(), 'YYYY') || '-' || lpad(nextval('seq_numero_pedido')::text, 5, '0'))
                         CHECK (numero_pedido ~ '^UC-[0-9]{4}-[0-9]{5}$'),   -- p. ej. UC-2026-01001
    id_cliente           INT           NOT NULL REFERENCES cliente(id_cliente) ON DELETE RESTRICT,
    id_carrito           INT           REFERENCES carrito(id_carrito) ON DELETE SET NULL,
    estado               VARCHAR(30)   NOT NULL DEFAULT 'creado'
                         CHECK (estado IN ('creado','pagado','pendiente_preparacion',
                                           'enviado','entregado','cancelado','con_incidencia')),
    paypal_order_id      VARCHAR(64)   UNIQUE,
    paypal_request_id    VARCHAR(38),
   
    envio_nombre         VARCHAR(250)  NOT NULL,       -- "nombre apellidos"
    envio_email          VARCHAR(254)  NOT NULL,
    envio_telefono       VARCHAR(30)   NOT NULL,
    envio_direccion      VARCHAR(200)  NOT NULL,       -- solo calle y número
    envio_ciudad         VARCHAR(80)   NOT NULL,
    envio_provincia      VARCHAR(80)   NOT NULL,
    envio_codigopostal   CHAR(5)       NOT NULL CHECK (envio_codigopostal ~ '^[0-9]{5}$'),
    envio_pais           VARCHAR(60)   NOT NULL DEFAULT 'España',
    -- Importes = computeTotals() de pricing.js (el servidor los recalcula siempre)
    subtotal             NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0),
    descuento            NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (descuento >= 0),
    gastos_envio         NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (gastos_envio >= 0),
    total                NUMERIC(10,2) NOT NULL CHECK (total >= 0),
    tipo_iva             NUMERIC(4,2)  NOT NULL DEFAULT 21.00,
    base_imponible       NUMERIC(10,2) NOT NULL,
    impuesto             NUMERIC(10,2) NOT NULL,       -- ivaIncluded
    fecha_creacion       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_actualizacion  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT chk_descuento  CHECK (descuento <= subtotal),
    -- Descuento: 0 o el 10 % del subtotal (DISCOUNT_RATE), con 0,005 de margen por el redondeo de JS.
    CONSTRAINT chk_descuento_tasa CHECK (descuento = 0 OR abs(descuento - subtotal * 0.10) <= 0.005),
    CONSTRAINT chk_total      CHECK (total = subtotal - descuento + gastos_envio),
    CONSTRAINT chk_desglose   CHECK (base_imponible + impuesto = total),
    -- IVA incluido = total - total/1,21 (tolerancia de 1 céntimo por redondeo JS)
    CONSTRAINT chk_iva        CHECK (abs(impuesto - round(total - total / (1 + tipo_iva / 100), 2)) <= 0.01),
    -- Envío: 6,90 €, gratis si subtotal - descuento >= 300 € (SHIPPING_COST / FREE_SHIPPING_FROM).
    CONSTRAINT chk_envio      CHECK (gastos_envio = CASE WHEN subtotal - descuento >= 300 THEN 0 ELSE 6.90 END)
);
CREATE INDEX idx_pedido_cliente ON pedido(id_cliente);
CREATE UNIQUE INDEX uq_pedido_carrito ON pedido(id_carrito);   
CREATE INDEX idx_pedido_estado  ON pedido(estado);

CREATE TABLE linea_pedido (
    id_lineapedido   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido        INT           NOT NULL REFERENCES pedido(id_pedido) ON DELETE CASCADE,
    id_producto      INT           NOT NULL REFERENCES producto(id_producto) ON DELETE RESTRICT,
    id_variante      INT           NOT NULL,
