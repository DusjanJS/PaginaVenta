-- =====================================================================
--  UCAM STEREO — PARTE 1: ESTRUCTURA (CREATE TABLE)        v5
--  PostgreSQL 15+ / Supabase — Soluciones Informáticas para la Empresa
--
--  Modelo alineado con el frontend (PaginaVenta: data/products.js,
--  lib/pricing.js, lib/orders.js, lib/events.js, context/*, pages/*).
--  Borra todas las tablas y datos anteriores y crea las 14 tablas,
--  índices, trigger, función, vista y RLS.
--  Ejecutar ANTES de 02_datos.sql.
--
--  Cambios respecto a v3 (todos para ser fieles al frontend):
--   · Variantes: cada producto tiene UNA variante base (finish/color de
--     products.js) + las de `variants`. Stock solo en variante_producto.
--     Desaparecen color y acabado (el frontend usa texto libre) y
--     precio_adicional (todas las variantes cuestan lo mismo).
--   · cliente: + rol ('cliente'|'admin'); se elimina el flag de primer
--     pedido: el descuento del 10 % dura un mes natural desde el alta
--     (pricing.js) -> función descuento_bienvenida_hasta().
--   · pedido: nº `UC-AAAA-NNNNN`, estados y reglas de envío/IVA del
--     frontend, email de contacto, sin notas/piso (ya no existen en el
--     formulario) ni código de descuento (el descuento es automático).
--   · pago: método `paypal_simulado`, resultado approved/declined.
--   · incidencia: datos del formulario de Soporte (pedido opcional).
--   · evento: 7 tipos (+ order.status_changed) y sesión del navegador.
--   · producto: sin gama ni galería (no existen en el frontend);
--     compatibilidad es texto; categoria.cta sustituye a titular.
--
--  Cambios de v5 (revisión de código):
--   · producto.especificaciones pasa de JSONB a JSON: JSONB reordena las
--     claves y la web pinta la ficha técnica en el orden de products.js.
--   · pedido.numero_pedido se genera en la base de datos (secuencia): el
--     contador del frontend es por pestaña y produciría números repetidos.
--   · Protección contra duplicados: un pago aprobado por pedido, un pedido
--     por carrito y un carrito activo por cliente.
--   · CHECK del descuento: solo 0 o el 10 % del subtotal (DISCOUNT_RATE).
-- =====================================================================

BEGIN;

